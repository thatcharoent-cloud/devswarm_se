"""
devswarm.agents.architect_schema — Software Architect schema, contract validator, and renderer.

Produces structured architecture design (ArchitectureDesign) with:
  - Stack decision with researched justification & sources
  - Folder structure and data models
  - Component list and interface CONTRACT STUBS (signatures, types, docstrings)
  - Architectural Decision Records (ADRs)
  - Security considerations and constraints for local implementers
Code renders .swarm/runs/<run_id>/artifacts/architecture.md.
"""

from __future__ import annotations

import re
from typing import Any
from pydantic import BaseModel, Field, field_validator


class InterfaceContract(BaseModel):
    """Interface contract stub file to be written into the repo."""
    path: str = Field(description="Target file path, e.g. src/calculator.py or src/interfaces/calc.py")
    content: str = Field(description="Python stub code with types, signatures, docstrings, and NotImplementedError")
    description: str = Field(default="", description="Summary of contract role")

    @field_validator("content")
    @classmethod
    def validate_python_syntax(cls, v: str) -> str:
        """Ensure stub code is syntactically valid Python that compiles."""
        try:
            compile(v, "<stub>", "exec")
        except SyntaxError as exc:
            raise ValueError(f"Contract stub contains invalid Python syntax: {exc}") from exc
        return v


class ADRRecord(BaseModel):
    """Architectural Decision Record."""
    id: str = Field(description="Identifier, e.g. ADR-001")
    title: str = Field(description="Decision title")
    status: str = Field(default="Accepted", description="Status (Accepted, Proposed, Superceded)")
    context: str = Field(description="Problem context and rationale")
    decision: str = Field(description="Specific technical choice made")
    consequences: str = Field(description="Positive and negative trade-offs")
    alternatives_considered: list[str] = Field(default_factory=list, description="Alternative options evaluated")


class CitedSource(BaseModel):
    """Source cited during architectural research."""
    title: str
    url: str
    retrieved_at: str = ""


class ArchitectureDesign(BaseModel):
    """Complete system architecture design generated by the Architect agent."""
    stack_decision: str = Field(description="Core technology stack, frameworks, and libraries selected")
    stack_justification: str = Field(description="Technical justification for stack choices")
    sources_cited: list[CitedSource] = Field(default_factory=list, description="Citations from web research")
    folder_structure: list[str] = Field(description="Proposed directory layout")
    data_models: list[str] = Field(default_factory=list, description="Core data models, classes, and types")
    components: list[str] = Field(description="Modular system components")
    contracts: list[InterfaceContract] = Field(description="Interface contract stubs with types and signatures")
    adrs: list[ADRRecord] = Field(default_factory=list, description="Architectural Decision Records")
    security_considerations: list[str] = Field(default_factory=list, description="Security architecture notes")
    implementer_constraints: list[str] = Field(
        default_factory=lambda: [
            "Small modules: maximum 150 lines per file",
            "Single responsibility: one primary class or concern per file",
            "Standard library only unless external dependency is explicitly approved",
            "Full type annotations and docstrings on public APIs",
        ],
        description="Guidelines and constraints for local coding agents",
    )

    @field_validator("contracts")
    @classmethod
    def validate_contracts(cls, v: list[InterfaceContract]) -> list[InterfaceContract]:
        if not v:
            raise ValueError("ArchitectureDesign must provide at least one interface contract stub.")
        return v


def render_architecture_markdown(design: ArchitectureDesign, run_id: str = "") -> str:
    """Render ArchitectureDesign into standard architecture.md markdown artifact."""
    lines: list[str] = [
        f"# Software Architecture & System Design",
        f"**Run ID:** `{run_id or 'unknown'}`\n",
        "## 1. Stack Decision & Justification",
        f"**Decision:** {design.stack_decision.strip()}\n",
        f"**Justification:** {design.stack_justification.strip()}",
        "",
        "## 2. Cited Sources & Documentation",
    ]

    if design.sources_cited:
        for s in design.sources_cited:
            lines.append(f"- [{s.title}]({s.url}) *(Retrieved: {s.retrieved_at or 'recent'})*")
    else:
        lines.append("- *(Standard library / built-in architecture)*")

    lines.extend([
        "",
        "## 3. Directory Layout & Folder Structure",
        "```text",
    ])
    for item in design.folder_structure:
        lines.append(item)
    lines.extend([
        "```",
        "",
        "## 4. Components & Data Models",
    ])

    lines.append("### Components")
    for comp in design.components:
        lines.append(f"- `{comp}`")

    lines.append("\n### Data Models")
    if design.data_models:
        for dm in design.data_models:
            lines.append(f"- {dm}")
    else:
        lines.append("- *(Standard scalar and collection types)*")

    lines.extend([
        "",
        "## 5. Interface Contract Stubs",
        "The platform creates these stubs to define strict API boundaries for implementers:",
    ])

    for contract in design.contracts:
        lines.extend([
            f"\n### `{contract.path}`",
            f"*{contract.description or 'Contract interface'}*",
            "```python",
            contract.content.strip(),
            "```",
        ])

    lines.extend([
        "",
        "## 6. Architectural Decision Records (ADRs)",
    ])
    if design.adrs:
        for adr in design.adrs:
            lines.extend([
                f"### {adr.id}: {adr.title} `[{adr.status}]`",
                f"**Context:** {adr.context}",
                f"**Decision:** {adr.decision}",
                f"**Consequences:** {adr.consequences}",
            ])
            if adr.alternatives_considered:
                lines.append(f"**Alternatives:** {', '.join(adr.alternatives_considered)}")
            lines.append("")
    else:
        lines.append("- *(No ADRs recorded)*")

    lines.extend([
        "## 7. Security Architecture Considerations",
    ])
    if design.security_considerations:
        for sec in design.security_considerations:
            lines.append(f"- 🛡️ {sec}")
    else:
        lines.append("- Standard input validation and bounds checking.")

    lines.extend([
        "",
        "## 8. Constraints for Local Implementers",
    ])
    for constraint in design.implementer_constraints:
        lines.append(f"- 📌 {constraint}")

    return "\n".join(lines)

