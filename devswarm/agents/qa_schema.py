"""
devswarm.agents.qa_schema — QA test-first schema and RED-check validator.

Enforces:
  1. QA writes unit tests from Acceptance Criteria (AC-1..n) and contract stubs.
  2. QA maps each test function to its corresponding AC-ID.
  3. Platform checks RED condition:
     - Tests compile and collect cleanly (no syntax or broken import errors).
     - Tests FAIL on unimplemented stubs for the right reason (AssertionError, NotImplementedError).
     - If syntax or import error occurs, sends output back once to fix; then needs_human.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import Any
from pydantic import BaseModel, Field, field_validator, model_validator

from devswarm.platform.sandbox import BaseSandbox

logger = logging.getLogger(__name__)


class QATestFile(BaseModel):
    """Test file generated by QA agent."""
    path: str = Field(description="Relative path to test file, e.g. tests/test_calculator.py")
    content: str = Field(description="Full pytest or unittest code")

    @field_validator("path")
    @classmethod
    def validate_test_path(cls, v: str) -> str:
        clean = v.strip().replace("\\", "/")
        if not (clean.startswith("tests/") or clean.startswith("test_") or clean.endswith("_test.py") or "/test_" in clean):
            raise ValueError(f"QA test path '{v}' must be located in tests/ or start with test_.")
        return clean

    @field_validator("content")
    @classmethod
    def validate_syntax(cls, v: str) -> str:
        try:
            compile(v, "<test_file>", "exec")
        except SyntaxError as exc:
            raise ValueError(f"Test file contains syntax error: {exc}") from exc
        return v


class QATestSuite(BaseModel):
    """Complete test-first suite generated by QA."""
    test_files: list[QATestFile] = Field(description="List of test files")
    ac_mapping: dict[str, list[str]] = Field(
        default_factory=dict,
        description="Mapping from AC-ID (e.g. AC-1) to list of test function names",
    )

    @model_validator(mode="before")
    @classmethod
    def normalize_input(cls, data: Any) -> Any:
        if isinstance(data, list):
            return {"test_files": data}
        if isinstance(data, dict):
            if "test_files" not in data:
                for alt_key in ("tests", "files", "test_cases", "test_suite"):
                    if alt_key in data and isinstance(data[alt_key], list):
                        data["test_files"] = data[alt_key]
                        break
        return data

    @field_validator("test_files")
    @classmethod
    def validate_has_tests(cls, v: list[QATestFile]) -> list[QATestFile]:
        if not v:
            raise ValueError("QATestSuite must contain at least one test file.")
        return v

    @model_validator(mode="after")
    def ensure_ac_mapping(self) -> QATestSuite:
        if not self.ac_mapping:
            mapping: dict[str, list[str]] = {}
            for tf in self.test_files:
                found = re.findall(r"def\s+(test_[a-zA-Z0-9_]+)\s*\(", tf.content)
                for fn in found:
                    ac_m = re.search(r"ac_?(\d+)", fn, re.IGNORECASE)
                    ac_id = f"AC-{ac_m.group(1)}" if ac_m else "AC-1"
                    mapping.setdefault(ac_id, []).append(fn)
            self.ac_mapping = mapping or {"AC-1": ["test_suite"]}
        return self


class QARedCheckError(Exception):
    """Base exception for red-check failures."""


class QASyntaxOrImportError(QARedCheckError):
    """Raised when tests fail to collect or have broken syntax/imports."""


class QAVacuousTestsError(QARedCheckError):
    """Raised when tests pass prematurely against unimplemented stubs."""


class RedCheckValidator:
    """Verifies that test suites compile, collect, and fail for the right reason."""

    @staticmethod
    async def validate_red_check(
        test_suite: QATestSuite,
        sandbox: BaseSandbox,
        worktree_dir: str = ".",
    ) -> tuple[bool, str]:
        """
        Runs RED-check in the sandbox.
        Returns (True, message) if tests collect and fail as expected,
        or raises QASyntaxOrImportError / QAVacuousTestsError.
        """
        # 1. Write test files into worktree
        for tf in test_suite.test_files:
            p = (Path(worktree_dir) / tf.path).resolve()
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(tf.content, encoding="utf-8")

        worktree_path = Path(worktree_dir)
        import shutil
        if worktree_path.exists():
            for p in worktree_path.iterdir():
                if p.is_dir() and not p.name.startswith("."):
                    if not p.name.isidentifier() and p.name not in ("tests", "docs", ".github", ".swarm"):
                        try:
                            shutil.rmtree(p)
                        except Exception:
                            pass

        tests_dir = worktree_path / "tests"
        if tests_dir.exists():
            (tests_dir / "__init__.py").touch(exist_ok=True)
            testpaths_cfg = "testpaths = tests\n"
        else:
            testpaths_cfg = ""

        conftest = worktree_path / "conftest.py"
        if not conftest.exists():
            conftest.write_text(
                "import sys\nfrom pathlib import Path\n"
                "repo_root = str(Path(__file__).parent.resolve())\n"
                "if repo_root not in sys.path:\n"
                "    sys.path.insert(0, repo_root)\n",
                encoding="utf-8",
            )
        pytest_ini = worktree_path / "pytest.ini"
        pytest_ini.write_text(f"[pytest]\npythonpath = .\n{testpaths_cfg}", encoding="utf-8")

        # 2. Check test collection (must compile and collect cleanly)
        collect_res = sandbox.run_command("pytest --collect-only -q", worktree_dir=worktree_dir)
        if collect_res.exit_code != 0:
            error_output = (collect_res.stderr or collect_res.stdout).strip()
            raise QASyntaxOrImportError(
                f"QA tests failed collection (syntax or import error):\n{error_output}"
            )

        # 3. Run test execution (must fail before implementation)
        run_res = sandbox.run_command("pytest -q", worktree_dir=worktree_dir)
        combined_output = (run_res.stdout + "\n" + run_res.stderr).strip()

        # If tests pass completely without implementation, they are vacuous
        if run_res.exit_code == 0:
            raise QAVacuousTestsError(
                "QA tests passed on unmodified/stubbed code. Tests must fail before implementation to verify behavior."
            )

        # If tests failed due to SyntaxError or ImportError during run without reaching stubs
        has_stub_failures = (
            "NotImplementedError" in combined_output
            or "AssertionError" in combined_output
            or "TypeError" in combined_output
            or "AttributeError" in combined_output
        )
        if not has_stub_failures and (
            "SyntaxError:" in combined_output
            or "ImportError:" in combined_output
            or "ModuleNotFoundError:" in combined_output
        ):
            raise QASyntaxOrImportError(
                f"QA tests crashed with syntax or import failure:\n{combined_output}"
            )

        # Non-zero exit code with assertion or NotImplementedError is successful RED condition
        logger.info("RED-check PASSED: Tests collected cleanly and failed against stubs as expected.")
        return True, "RED-check PASSED: Tests fail against stubs as expected."
