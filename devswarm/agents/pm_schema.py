"""
devswarm.agents.pm_schema — Product Manager agent schema, validator, and spec renderer.

Produces structured specification (PMSpecification) with:
  - Problem statement & user stories
  - Numbered acceptance criteria (AC-1..n)
  - Non-goals, assumptions, open questions
  - Milestones and risks
Code renders .swarm/runs/<run_id>/artifacts/spec.md.
"""

from __future__ import annotations

import re
from typing import Any
from pydantic import BaseModel, Field, field_validator, model_validator


class AcceptanceCriterion(BaseModel):
    """Numbered, observable, and testable acceptance criterion."""
    id: str = Field(description="Unique identifier, e.g. AC-1, AC-2")
    description: str = Field(description="Clear behavioral expectation")
    verification_method: str = Field(
        default="Automated unit test",
        description="How QA verifies it, e.g. automated unit test, CLI assertion",
    )
    observable_result: str = Field(
        default="Expected output matches specification without errors",
        description="Expected observable outcome or return value",
    )

    @model_validator(mode="before")
    @classmethod
    def normalize_ac(cls, data: Any) -> Any:
        if isinstance(data, dict):
            # Fallback for common alternate keys
            if "description" not in data or not data.get("description"):
                for k in ("desc", "text", "statement", "criterion", "name"):
                    if k in data and data[k]:
                        data["description"] = str(data[k])
                        break
            if "verification_method" not in data or not data.get("verification_method"):
                for k in ("verification", "test", "verification_method", "test_method", "method"):
                    if k in data and data[k]:
                        data["verification_method"] = str(data[k])
                        break
            if "observable_result" not in data or not data.get("observable_result"):
                for k in ("result", "expected", "expected_result", "observable_outcome", "outcome"):
                    if k in data and data[k]:
                        data["observable_result"] = str(data[k])
                        break
        return data

    @field_validator("id")
    @classmethod
    def validate_ac_id(cls, v: str) -> str:
        clean = v.strip().upper()
        if not re.match(r"^AC-\d+$", clean):
            raise ValueError(f"Acceptance criterion ID '{v}' must match pattern AC-1, AC-2, etc.")
        return clean

    @field_validator("description")
    @classmethod
    def validate_description(cls, v: str) -> str:
        if len(v.strip()) < 8:
            raise ValueError("Acceptance criterion description must be at least 8 characters.")
        return v.strip()


class Milestone(BaseModel):
    """Milestone / timeline target."""
    title: str
    target: str


class PMSpecification(BaseModel):
    """Complete product specification generated by the PM agent."""
    problem_statement: str = Field(
        default="Core functional requirements and behavioral specifications.",
        description="Core problem or user need being addressed",
    )
    user_stories: list[str] = Field(default_factory=list, description="User story statements: As a... I want... So that...")
    acceptance_criteria: list[AcceptanceCriterion] = Field(description="List of testable acceptance criteria")
    non_goals: list[str] = Field(default_factory=list, description="Explicitly excluded features or scope")
    assumptions: list[str] = Field(default_factory=list, description="Working technical or domain assumptions")
    open_questions: list[str] = Field(default_factory=list, description="Unresolved questions for human product owner")
    milestones: list[Milestone] = Field(default_factory=list, description="Delivery phases or milestones")
    risks: list[str] = Field(default_factory=list, description="Technical, product, or delivery risks")

    @model_validator(mode="before")
    @classmethod
    def normalize_pm_data(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "problem_statement" not in data or not data["problem_statement"]:
                for alt_k in ("summary", "overview", "description", "problem", "goal"):
                    if alt_k in data and data[alt_k]:
                        data["problem_statement"] = str(data[alt_k])
                        break
            if "acceptance_criteria" not in data:
                for alt_k in ("criteria", "requirements", "acceptance_criterion", "acs"):
                    if alt_k in data and isinstance(data[alt_k], list):
                        data["acceptance_criteria"] = data[alt_k]
                        break
        return data

    @field_validator("acceptance_criteria")
    @classmethod
    def validate_criteria(cls, v: list[AcceptanceCriterion]) -> list[AcceptanceCriterion]:
        if not v:
            raise ValueError("PMSpecification must contain at least one acceptance criterion.")
        seen_ids: set[str] = set()
        for ac in v:
            if ac.id in seen_ids:
                raise ValueError(f"Duplicate acceptance criterion ID: '{ac.id}'")
            seen_ids.add(ac.id)
        return v


def render_spec_markdown(spec: PMSpecification, run_id: str = "") -> str:
    """Render PMSpecification into standard spec.md markdown artifact."""
    lines: list[str] = [
        f"# Product Feature Specification",
        f"**Run ID:** `{run_id or 'unknown'}`\n",
        "## 1. Problem Statement",
        spec.problem_statement.strip(),
        "",
        "## 2. User Stories",
    ]

    if spec.user_stories:
        for s in spec.user_stories:
            lines.append(f"- {s.strip()}")
    else:
        lines.append("- *(None provided)*")

    lines.extend([
        "",
        "## 3. Numbered Acceptance Criteria",
        "| ID | Description | Verification Method | Observable Result |",
        "|---|---|---|---|",
    ])

    for ac in spec.acceptance_criteria:
        lines.append(f"| `{ac.id}` | {ac.description} | {ac.verification_method} | {ac.observable_result} |")

    lines.extend([
        "",
        "## 4. Scope & Non-Goals",
    ])
    if spec.non_goals:
        for ng in spec.non_goals:
            lines.append(f"- **Out of scope:** {ng.strip()}")
    else:
        lines.append("- *(No explicit non-goals recorded)*")

    lines.extend([
        "",
        "## 5. Working Assumptions",
    ])
    if spec.assumptions:
        for a in spec.assumptions:
            lines.append(f"- {a.strip()}")
    else:
        lines.append("- *(None)*")

    lines.extend([
        "",
        "## 6. Open Questions for Human Product Owner",
    ])
    if spec.open_questions:
        for q in spec.open_questions:
            lines.append(f"- ❓ {q.strip()}")
    else:
        lines.append("- ✅ *(No unresolved open questions)*")

    lines.extend([
        "",
        "## 7. Delivery Milestones",
    ])
    if spec.milestones:
        for m in spec.milestones:
            lines.append(f"- **{m.title}:** {m.target}")
    else:
        lines.append("- Phase 1: Core Implementation and Testing")

    lines.extend([
        "",
        "## 8. Technical & Delivery Risks",
    ])
    if spec.risks:
        for r in spec.risks:
            lines.append(f"- ⚠️ {r.strip()}")
    else:
        lines.append("- *(Low risk: straightforward implementation)*")

    return "\n".join(lines)

